"""``museport llmc-sycl``: put llm.c's ported pieces back together as one project (plan item J3).

Each port lives in its own evidence folder with a contract ``main`` made for checking. This
builds ``llm.c-sycl/`` the way llm.c is laid out:

- ``dev/sycl/<kernel>/``: Muse's SYCL port of each ``dev/cuda`` kernel file, as last compiled
  and graded correct, unchanged. A Makefile builds them for the CPU, NVIDIA or AMD.
- ``llmc/``: llm.c's plain-C host headers (utils, tokenizer, dataloader, rand), unchanged.
- ``LICENSE`` (llm.c's, MIT) and the starter-pack download script.

The trainer and llm.c's own test are added by later steps (Muse ports them).
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from .port import grade_run, last_compiled_sources

# The kernel ports that make up dev/sycl: the post-fix runs, with softmax_forward taken from
# the rerun that passes (run 2's softmax_forward fails the hidden check).
KERNELS: tuple[tuple[str, str], ...] = (
    *(("port-llmc-tier1-run2", i) for i in (
        "t1-gelu-forward", "t1-gelu-backward", "t1-residual-forward", "t1-permute",
        "t1-crossentropy-forward", "t1-crossentropy-softmax-backward", "t1-encoder-forward",
        "t1-encoder-backward", "t1-adamw", "t1-fused-residual-forward")),
    *(("port-llmc-tier23-run2", i) for i in (
        "t2-global-norm", "t2-layernorm-forward", "t2-classifier-fused", "t2-layernorm-backward",
        "t3-matmul-forward", "t3-matmul-backward", "t3-trimat-forward",
        "t3-matmul-backward-bias")),
    ("port-llmc-softmax-rerun-2", "t2-softmax-forward"),
)
HOST_HEADERS = ("utils.h", "tokenizer.h", "dataloader.h", "rand.h")

MAKEFILE = """\
# Muse's SYCL ports of llm.c's dev/cuda kernel files (generated by `museport llmc-sycl`).
#   make                    build every port for the CPU device (JIT, spir64)
#   make TARGET=nvidia      ... for NVIDIA (intel/llvm with the CUDA backend)
#   make TARGET=amd AMD_ARCH=gfx950
# Ports that call oneMath need ONEMATH_PREFIX (a oneMath install with the matching backend).
SYCL_CXX ?= icpx
TARGET ?= cpu
AMD_ARCH ?= gfx90a
ifeq ($(TARGET),nvidia)
  TARGET_FLAGS = -fsycl-targets=nvptx64-nvidia-cuda
else ifeq ($(TARGET),amd)
  TARGET_FLAGS = -fsycl-targets=amdgcn-amd-amdhsa -Xsycl-target-backend=amdgcn-amd-amdhsa \\
                 --offload-arch=$(AMD_ARCH)
else
  TARGET_FLAGS =
endif
ONEMATH_FLAGS = -I$(ONEMATH_PREFIX)/include -Wl,--no-as-needed -L$(ONEMATH_PREFIX)/lib \\
                -Wl,-rpath,$(ONEMATH_PREFIX)/lib -lonemath

KERNELS = {kernels}
all: $(addprefix build/,$(KERNELS))
build:
\tmkdir -p build
{rules}
clean:
\trm -rf build
.PHONY: all clean
"""


def _item(evidence: Path, batch: str, item: str) -> dict[str, Any]:
    d = evidence / batch / item
    task = json.loads((d / "task" / "task.json").read_text())
    srcs = last_compiled_sources(d / "trace.jsonl")
    if not srcs:
        raise ValueError(f"{batch}/{item}: the model never compiled")
    stem = task["museport"]["source"].rsplit("/", 1)[-1].removesuffix(".cu")
    return {"batch": batch, "item": item, "dir": d, "task": task, "sources": srcs,
            "stem": stem, "onemath": any("onemath" in f.lower()
                                         for f in task.get("base_flags", []))}


def assemble(evidence: Path, llmc: Path, out: Path) -> dict[str, Any]:
    """Write ``out`` (``llm.c-sycl``) from the evidence and an llm.c checkout."""
    dev = out / "dev" / "sycl"
    if dev.exists():
        shutil.rmtree(dev)
    dev.mkdir(parents=True)
    rows, rules = [], []
    for batch, item in KERNELS:
        it = _item(evidence, batch, item)
        dest = dev / it["stem"]
        dest.mkdir()
        for s in it["sources"]:
            shutil.copyfile(it["dir"] / "port" / s, dest / Path(s).name)
        ev = json.loads((evidence / batch / "summary.json").read_text())
        row = next(r for r in ev["items"] if r["item"] == item)
        rows.append({"kernel": it["stem"], "sources": [Path(s).name for s in it["sources"]],
                     "evidence": f"evidence/{batch}/{item}", "onemath": it["onemath"],
                     "hidden_grade": (row.get("evaluation") or {}).get("verify_summary"),
                     "turns": row.get("iterations"), "cost_usd": row.get("cost_usd")})
        srcs = " ".join(f"{it['stem']}/{Path(s).name}" for s in it["sources"])
        rules.append(f"build/{it['stem']}: {srcs} | build\n"
                     f"\t$(SYCL_CXX) -fsycl -O2 $(TARGET_FLAGS) {srcs} -o $@"
                     + (" $(ONEMATH_FLAGS)" if it["onemath"] else ""))
    (dev / "Makefile").write_text(MAKEFILE.format(
        kernels=" ".join(r["kernel"] for r in rows), rules="\n".join(rules)))
    (dev / "PROVENANCE.json").write_text(json.dumps(rows, indent=2) + "\n")
    (dev / "README.md").write_text(_dev_readme(rows))
    (out / "llmc").mkdir(parents=True, exist_ok=True)
    for h in HOST_HEADERS:
        shutil.copyfile(llmc / "llmc" / h, out / "llmc" / h)
    shutil.copyfile(llmc / "LICENSE", out / "LICENSE")
    (out / "dev").mkdir(exist_ok=True)
    script = "download_starter_pack.sh"
    shutil.copyfile(llmc / "dev" / script, out / "dev" / script)
    return {"kernels": rows}


def _dev_readme(rows: list[dict[str, Any]]) -> str:
    md = ["# dev/sycl: llm.c's kernel files, ported to SYCL by Muse", "",
          "Each folder holds Muse's port of one llm.c `dev/cuda` file, exactly as Muse last "
          "compiled it and as the hidden check graded it. `make` builds them all; ports that "
          "call oneMath need `ONEMATH_PREFIX`.", "",
          "| kernel | source | hidden grade | Muse turns | cost | evidence |",
          "|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| `{r['kernel']}` | {', '.join(r['sources'])} | {r['hidden_grade']} "
                  f"| {r['turns']} | ${r['cost_usd']:.4f} | `{r['evidence']}` |")
    return "\n".join(md) + "\n"


def check(evidence: Path, out: Path, work: Path) -> list[dict[str, Any]]:
    """Grade every dev/sycl port in ``out`` with its own hidden check, as copied (on the CPU)."""
    results = []
    for batch, item in KERNELS:
        it = _item(evidence, batch, item)
        ev = grade_run(it["dir"] / "task" / "task.json", out / "dev" / "sycl" / it["stem"],
                       it["dir"] / "trace.jsonl", work / it["stem"])
        results.append({"kernel": it["stem"], **ev})
    return results
