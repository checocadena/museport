"""Harness specs for llm.c's ``dev/cuda`` Tier 1 kernels (karpathy/llm.c, surveyed at f1e2ace).

Each llm.c dev file checks itself: its ``main`` runs a CPU reference function and compares
the GPU result with ``validate_result``. That check lives in the file the agent edits, so
it cannot be the hidden check. A ``KernelSpec`` says how to build an independent one:

- which CPU reference functions to extract (they become the hidden reference program);
- which kernel variants the file's dispatcher offers (``kernel_num``), all of which the port
  must keep;
- the inputs (generated by museport, like llm.c's ``make_random_*``), the outputs, and the
  calls that compute them on the CPU and through the original GPU dispatcher.

Sizes are reduced from llm.c's (B=8, T=1024, V=50257) so a CPU device can run the check;
the spec's ``note`` says what changed. Tolerances are llm.c's own fp32 values: llm.c passes
an element when ``|gpu - cpu| <= tol + |cpu| * FLT_EPSILON``, which is the toolkit's
``atol=tol, rtol=FLT_EPSILON``.
"""

from __future__ import annotations

from dataclasses import dataclass

FLT_EPSILON = 1.1920929e-07


@dataclass(frozen=True)
class Array:
    """An input (``init``: ``uniform`` in [-1, 1), ``unit`` in [0, 1), ``one`` (all 1.0),
    ``int:<C expr>`` for ints in [0, expr)) or an output (``init``: ``zeros`` or
    ``input:<name>``)."""

    name: str
    count: str  # C expression over the size names
    dtype: str = "f32"  # f32 | i32
    init: str = "uniform"
    device_count: str | None = None  # device buffer size when larger than `count`


@dataclass(frozen=True)
class KernelSpec:
    file: str
    cpu_functions: tuple[str, ...]
    variants: tuple[int, ...]
    sizes: tuple[tuple[str, int], ...]  # passed on the command line, in this order
    inputs: tuple[Array, ...]
    outputs: tuple[Array, ...]
    cpu_call: str  # host names
    gpu_call: str  # device pointers are d_<name>; `k` is the kernel_num
    tol: float
    note: str = ""
    host_prep: str = ""  # C run in both mains after the inputs are read (same on host)
    gpu_prelude: str = ""  # C run in the harness main before the variants (device setup)
    keep_in_harness: tuple[str, ...] = ()  # CPU functions the harness keeps (input setup only)
    extra_includes: tuple[str, ...] = ()  # headers the fp32 build needs (put before common.h)
    keep_cublas: bool = False  # Tier 3: common.h keeps its cuBLAS setup (the file calls cuBLAS)
    keep_cublaslt: bool = False  # ...and its cuBLASLt setup (only files that call cuBLASLt)
    output_post: str = ""  # C run on the host outputs in both mains before they are written
    base_flags: tuple[str, ...] = ()  # compile flags for the port (default: the toolkit's -O2)
    check_flags: tuple[str, ...] = ()  # extra flags for check_harness (SYCLomatic's raw output)

    @property
    def stem(self) -> str:
        return self.file.removesuffix(".cu")


